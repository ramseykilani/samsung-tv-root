class Linen(Design):
    name = 'linen'
    kind = 'liner'
    width_mm = 40.0
    lip_mm = 5.0
    h_outer = 8.0
    note = 'linen-wrapped liner sloping to a small gilt sight lip'

    def profile(self):
        return [
            (2.0, seg_quarter_up(0, 2, 8.0, 10.0), 1),
            (33.5, seg_cove(2, 10.0, 33.5, 5.5, 0.6), 1),        # linen slope
            (34.5, seg_line(33.5, 5.5, 34.5, 5.0), 2),
            (39.0, seg_bead(34.5, 39, 5.0, 2.0), 3),             # gilt lip
            (40.0, seg_quarter_down(39, 40, 5.0, 2.5), 3),
        ]

    def ornament(self, s, a, reg, ctx):
        A, px, rng = ctx['A'], ctx['px_mm'], ctx['rng']
        p = 0.85                                                  # thread pitch, mm
        na = int(round(A / (p * px)))
        wa = np.cos(math.pi * na * a / A) ** 2                    # weft threads across
        ws = np.cos(math.pi * s / p) ** 2                         # warp threads along
        chk = np.sign(np.sin(math.pi * s / p) * np.sin(math.pi * na * a / A))
        weave = 0.5 * (ws * (1 + chk) + wa * (1 - chk)) * 0.5
        slub = spectral_noise(rng, ctx['S'], A, 0.22 * px, 2.5 * px)
        slub2 = spectral_noise(rng, ctx['S'], A, 2.5 * px, 0.22 * px)
        self._slub = (slub, slub2)
        return np.where(reg == 1, 0.006 * weave + 0.004 * slub + 0.003 * slub2, 0).astype(F32)

    def material(self, ctx, H, reg):
        rng, S, A, px = ctx['rng'], ctx['S'], ctx['A'], ctx['px_mm']
        slub, slub2 = self._slub
        blot = spectral_noise(rng, S, A, 10 * px, 25 * px)
        lin = np.array([0.56, 0.47, 0.335], F32)
        fine = spectral_noise(rng, S, A, 0.35 * px, 0.35 * px)
        alb_l = lin * (1 + 0.035 * slub + 0.035 * slub2 + 0.05 * fine + 0.02 * blot)[..., None]
        gm = gilt_material(ctx, H, reg, burnish_regions=(3,), matte_regions=(2,), sand_regions=(), wear_amt=0.6)
        is_lin = (reg == 1)
        hook = gm['ao_hook']

        def ao_hook(ao):
            m = hook(ao)
            m['alb'] = np.where(is_lin[..., None], alb_l, m['alb']).astype(F32)
            m['rough'] = np.where(is_lin, 0.9, m['rough']).astype(F32)
            m['f0'] = np.where(is_lin[..., None], 0.03, m['f0']).astype(F32)
            m['metal'] = np.where(is_lin, 0.0, m['metal']).astype(F32)
            return m
        gm['ao_hook'] = ao_hook
        return gm


