SCREEN_PX_PER_MM = 1920 / 1208.7          # CSS px per mm on the 55" Frame
DENS = 1.5 * SCREEN_PX_PER_MM              # texture px per mm (final)
SS = 2                                     # supersampling factor while rendering
TILE = {'t': 3072, 'b': 3072, 'l': 2048, 'r': 2048}  # final texture length along each side (px)
JPEG_Q = 90

F32 = np.float32
TAU = 2 * math.pi


# ------------------------------------------------------------------ small maths helpers
def norm(v):
    v = np.asarray(v, dtype=np.float64)
    return v / np.linalg.norm(v)


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3 - 2 * t)


def mix(a, b, t):
    return a + (b - a) * t


def spectral_noise(rng, S, A, ls, la):
    """Gaussian-filtered white noise, std 1, periodic along both axes. ls, la = correlation lengths in px."""
    w = rng.standard_normal((S, A)).astype(F32)
    F = np.fft.rfft2(w)
    ks = np.fft.fftfreq(S)[:, None].astype(F32)
    ka = np.fft.rfftfreq(A)[None, :].astype(F32)
    G = np.exp(-2 * math.pi ** 2 * ((ks * ls) ** 2 + (ka * la) ** 2)).astype(F32)
    n = np.fft.irfft2(F * G, s=(S, A)).astype(F32)
    n -= n.mean()
    sd = n.std()
    return n / (sd if sd > 0 else 1)


def periodic_warp(rng, A, period_px, amp, octaves=3):
    """A smooth periodic 1-D function along the length (len A)."""
    a = np.arange(A, dtype=F32)
    out = np.zeros(A, F32)
    base = max(1, int(round(A / period_px)))
    for o in range(octaves):
        k = base * (2 ** o)
        out += (amp / (1.6 ** o)) * np.sin(TAU * k * a / A + rng.uniform(0, TAU)).astype(F32)
    return out


# ------------------------------------------------------------------ profile primitives (s, h in mm)
def seg_line(s0, h0, s1, h1):
    return lambda s: h0 + (h1 - h0) * np.clip((s - s0) / (s1 - s0), 0, 1)


def seg_cove(s0, h0, s1, h1, depth):      # concave hollow below the chord
    def f(s):
        t = np.clip((s - s0) / (s1 - s0), 0, 1)
        return h0 + (h1 - h0) * t - depth * np.sin(math.pi * t)
    return f


def seg_round(s0, h0, s1, h1, bulge):     # convex swell above the chord
    def f(s):
        t = np.clip((s - s0) / (s1 - s0), 0, 1)
        return h0 + (h1 - h0) * t + bulge * np.sin(math.pi * t)
    return f


def seg_ogee(s0, h0, s1, h1):             # S-curve
    def f(s):
        t = np.clip((s - s0) / (s1 - s0), 0, 1)
        return h0 + (h1 - h0) * (0.5 - 0.5 * np.cos(math.pi * t))
    return f


def seg_quarter_up(s0, s1, h0, h1):       # vertical at s0, flat at s1 (an outer edge rolling over)
    def f(s):
        t = np.clip((s - s0) / (s1 - s0), 0, 1)
        return h0 + (h1 - h0) * np.sqrt(np.clip(1 - (1 - t) ** 2, 0, 1))
    return f


def seg_quarter_down(s0, s1, h0, h1):     # flat at s0, vertical at s1 (a sight edge rolling over)
    def f(s):
        t = np.clip((s - s0) / (s1 - s0), 0, 1)
        return h1 + (h0 - h1) * np.sqrt(np.clip(1 - t ** 2, 0, 1))
    return f


def seg_bead(s0, s1, base, height=None):  # half-round bead sitting on `base`
    c, r = (s0 + s1) / 2, (s1 - s0) / 2
    hh = r if height is None else height
    return lambda s: base + hh * np.sqrt(np.clip(1 - ((s - c) / r) ** 2, 0, 1))


def eval_profile(segs, s):
    """segs: [(s_end, func, region)], ascending. Returns h(s), region(s)."""
    h = np.zeros_like(s, dtype=F32)
    reg = np.zeros(s.shape, dtype=np.int16)
    s_prev = -1e9
    for s_end, f, r in segs:
        m = (s >= s_prev) & (s < s_end)
        h[m] = f(s[m])
        reg[m] = r
        s_prev = s_end
    m = s >= s_prev
    if m.any():
        f, r = segs[-1][1], segs[-1][2]
        h[m] = f(s[m])
        reg[m] = r
    return h, reg


# ------------------------------------------------------------------ the room
KEY_DIR = norm([-0.36, 0.80, 0.48])      # towards the light: above, a little left, in front of the wall
KEY_RGB = np.array([1.00, 0.95, 0.87], F32) * 1.3
KEY_SIGMA = 0.19                          # angular size of the soft key (rad, gaussian)
EXPOSURE = 1.0


def env_radiance(d, blur):
    """Room radiance seen along world direction d (..., 3), y up, z out of the wall. blur in ~radians."""
    y = d[..., 1]
    b = np.maximum(blur, 0.02)
    ceil = smoothstep(-b, 0.55 + b, y)              # 0 at the horizon -> 1 looking up
    floor = smoothstep(-b, 0.5 + b, -y)
    wall = np.array([0.165, 0.156, 0.143], F32)
    ceiling = np.array([0.34, 0.33, 0.315], F32)
    floorc = np.array([0.070, 0.055, 0.040], F32)
    out = wall + (ceiling - wall) * ceil[..., None]
    out = out + (floorc - wall) * floor[..., None]
    # a dim second window on the far side so the shadow side is not dead
    side = smoothstep(0.2, 0.9, d[..., 0]) * smoothstep(-0.2, 0.5, y)
    out = out + np.array([0.05, 0.055, 0.06], F32) * side[..., None]
    return out.astype(F32)


def fibonacci_dirs(n):
    i = np.arange(n) + 0.5
    phi = np.arccos(1 - 2 * i / n)
    th = math.pi * (1 + 5 ** 0.5) * i
    return np.stack([np.cos(th) * np.sin(phi), np.sin(th) * np.sin(phi), np.cos(phi)], -1).astype(F32)


AMB_DIRS = fibonacci_dirs(96)
AMB_RAD = env_radiance(AMB_DIRS, np.full(len(AMB_DIRS), 0.3, F32))


def key_samples():
    """Directions sampling the soft key (gaussian-ish disc)."""
    up = np.array([0, 1, 0.0])
    t1 = norm(np.cross(up, KEY_DIR)) if abs(KEY_DIR[1]) < 0.99 else np.array([1, 0, 0.0])
    t2 = np.cross(KEY_DIR, t1)
    dirs = [KEY_DIR]
    for ring, n in ((0.7, 6), (1.5, 8)):
        for k in range(n):
            a = TAU * (k + 0.5 * (ring > 1)) / n
            off = ring * KEY_SIGMA * (math.cos(a) * t1 + math.sin(a) * t2)
            dirs.append(norm(KEY_DIR + off))
    return [np.asarray(d, F32) for d in dirs]


KEY_DIRS = key_samples()

SIDES = {
    #      e_out (outward, world)   e_along                   view vector (eye ~2.5 m away, at centre)
    't': (np.array([0, 1, 0], F32), np.array([1, 0, 0], F32), norm([0, -0.14, 1])),
    'b': (np.array([0, -1, 0], F32), np.array([1, 0, 0], F32), norm([0, 0.14, 1])),
    'l': (np.array([-1, 0, 0], F32), np.array([0, -1, 0], F32), norm([0.24, 0, 1])),
    'r': (np.array([1, 0, 0], F32), np.array([0, -1, 0], F32), norm([-0.24, 0, 1])),
}


# ------------------------------------------------------------------ height-field sampling
class Field:
    def __init__(self, H, h_outer, h_inner, px_mm):
        self.H = H
        self.S, self.A = H.shape
        self.px_mm = px_mm
        self.P = 0
        self.h_outer, self.h_inner = h_outer, h_inner
        self._pad(64)

    def _pad(self, P):
        if P <= self.P:
            return
        self.P = P
        top = np.full((P, self.A), self.h_outer, F32)
        bot = np.full((P, self.A), self.h_inner, F32)
        self.Hp = np.concatenate([top, self.H, bot], 0)

    def shifted(self, ds, da):
        ds, da = int(ds), int(da)
        if abs(ds) >= self.P:
            self._pad(abs(ds) + 8)
        rows = self.Hp[self.P + ds:self.P + ds + self.S]
        return np.roll(rows, -da, axis=1) if da else rows


def horizon_ao(fld, radius_mm=9.0, ndir=8):
    steps = sorted(set(int(round(x)) for x in np.geomspace(1, radius_mm * fld.px_mm, 12)))
    H = fld.H
    acc = np.zeros_like(H)
    for k in range(ndir):
        ang = TAU * (k + 0.5) / ndir
        cs, ca = math.cos(ang), math.sin(ang)
        mx = np.zeros_like(H)
        for t in steps:
            dh = fld.shifted(round(cs * t), round(ca * t)) - H
            np.maximum(mx, dh / (t / fld.px_mm), out=mx)
        acc += 1 - mx / np.sqrt(1 + mx * mx)     # 1 - sin(horizon elevation)
    return acc / ndir


def light_visibility(fld, Ldir, e_out, e_al, max_mm=70.0):
    lo, la, lz = float(Ldir @ e_out), float(Ldir @ e_al), float(Ldir[2])
    lh = math.hypot(lo, la)
    if lh < 1e-4:
        return np.ones_like(fld.H)
    us, ua, slope = -lo / lh, la / lh, lz / lh   # per mm travelled in the plane: s, a, rise
    steps = sorted(set(int(round(x)) for x in np.geomspace(1, max_mm * fld.px_mm, 26)))
    H = fld.H
    occ = np.zeros(H.shape, bool)
    for t in steps:
        sh = fld.shifted(round(us * t), round(ua * t))
        occ |= sh > H + slope * (t / fld.px_mm) + 0.05
    return (~occ).astype(F32)


# ------------------------------------------------------------------ shading
def shade(H, mat, side, px_mm, h_outer, h_inner):
    e_out, e_al, V = SIDES[side]
    S, A = H.shape
    # local normal: n = (dh/ds) e_out - (dh/da) e_along + z
    dhds = np.gradient(H, axis=0) * px_mm
    dhda = (np.roll(H, -1, 1) - np.roll(H, 1, 1)) * 0.5 * px_mm
    N = (dhds[..., None] * e_out + (-dhda)[..., None] * e_al)
    N = N + np.array([0, 0, 1], F32)
    N /= np.linalg.norm(N, axis=-1, keepdims=True)
    N = N.astype(F32)

    fld = Field(H, h_outer, h_inner, px_mm)
    ao = horizon_ao(fld)
    if 'ao_hook' in mat:
        mat = mat['ao_hook'](ao)

    alb, rough, f0, metal = mat['alb'], mat['rough'], mat['f0'], mat['metal']

    # --- key light (soft, self-shadowed)
    key_diff = np.zeros((S, A), F32)
    key_vis_mean = np.zeros((S, A), F32)
    for L in KEY_DIRS:
        vis = light_visibility(fld, L, e_out, e_al)
        key_diff += vis * np.maximum(N @ L, 0)
        key_vis_mean += vis
    key_diff /= len(KEY_DIRS)
    key_vis_mean /= len(KEY_DIRS)

    # --- ambient irradiance from the room (cosine-weighted), occluded by AO
    amb = np.zeros((S, A, 3), F32)
    for d, rad in zip(AMB_DIRS, AMB_RAD, strict=True):
        amb += np.maximum(N @ d, 0)[..., None] * rad
    amb *= 4.0 / len(AMB_DIRS)
    amb *= ao[..., None]

    diffuse = alb * (key_diff[..., None] * KEY_RGB + amb)

    # --- specular: room reflection blurred by roughness + the key as a gaussian lobe
    NdV = np.clip(N @ V, 1e-3, 1)
    R = 2 * NdV[..., None] * N - V
    sig_r = np.clip(rough, 0.03, 1.2) * 0.75
    env = env_radiance(R, sig_r)
    fres = f0 + (1 - f0) * ((1 - NdV) ** 5)[..., None] * (1 - rough[..., None]) ** 2
    cosk = np.clip(R @ KEY_DIR, -1, 1)
    ang2 = np.arccos(cosk) ** 2
    ssum = KEY_SIGMA ** 2 + sig_r ** 2
    lobe = (1.0 / (TAU * KEY_SIGMA ** 2)) * (KEY_SIGMA ** 2 / ssum) * np.exp(-ang2 / (2 * ssum))
    spec_occ = np.clip(ao * 1.15 - 0.15, 0, 1) ** 1.5
    spec = fres * (env * spec_occ[..., None] + (lobe * key_vis_mean)[..., None] * KEY_RGB)

    col = diffuse * (1 - metal[..., None]) + spec
    return col * EXPOSURE


def finish(col, rng):
    """Downsample SSxSS, tone-map with a soft shoulder, sRGB-encode, dither, quantise."""
    S, A, _ = col.shape
    col = col[:S - S % SS, :A - A % SS].reshape(S // SS, SS, A // SS, SS, 3).mean((1, 3))
    knee = 0.72
    over = np.maximum(col - knee, 0)
    col = np.where(col > knee, knee + (1 - knee) * (1 - np.exp(-over / (1 - knee))), col)
    col = np.clip(col, 0, 1)
    srgb = np.where(col <= 0.0031308, col * 12.92, 1.055 * np.power(col, 1 / 2.4) - 0.055)
    tri = rng.random(srgb.shape, dtype=F32) - rng.random(srgb.shape, dtype=F32)   # +-1 LSB triangular
    q = np.clip(np.round(srgb * 255 + tri), 0, 255).astype(np.uint8)
    return q


def orient(img, side):
    if side == 't':
        return img
    if side == 'b':
        return img[::-1]
    if side == 'l':
        return img.transpose(1, 0, 2)
    return img.transpose(1, 0, 2)[:, ::-1]


# ------------------------------------------------------------------ materials
GOLD = np.array([1.00, 0.675, 0.265], F32)      # toned water-gilt leaf (pure gold is ~1.0, .77, .34)
BOLE = np.array([0.28, 0.095, 0.045], F32)     # red-brown clay under the leaf
GRIME = np.array([0.045, 0.028, 0.012], F32)   # old toning / dust in the hollows


def wood_pores(rng, S, A, density, length_px, depth):
    m = (rng.random((S, A)) < density).astype(F32)
    out = np.zeros_like(m)
    for k in range(int(length_px)):
        out += np.roll(m, k, 1)
    return 1 - depth * np.clip(out, 0, 1)


def gilt_material(ctx, H, reg, burnish_regions, matte_regions, sand_regions, wear_amt=0.7, back_regions=()):
    """Water gilding: burnished on raised members, matte in hollows; worn to bole on high edges; toned."""
    rng, S, A, px = ctx['rng'], ctx['S'], ctx['A'], ctx['px_mm']
    burn = np.isin(reg, burnish_regions).astype(F32)
    sand = np.isin(reg, sand_regions).astype(F32)
    back = np.isin(reg, back_regions).astype(F32)
    n_fine = spectral_noise(rng, S, A, 0.25 * px, 0.6 * px)
    n_mid = spectral_noise(rng, S, A, 3 * px, 9 * px)
    n_low = spectral_noise(rng, S, A, 12 * px, 60 * px)
    rough = mix(np.full((S, A), 0.36, F32), np.full((S, A), 0.085, F32), burn)
    rough = rough + sand * 0.2 + 0.03 * n_fine
    f0 = GOLD * (1 + 0.035 * n_mid + 0.02 * n_fine + 0.09 * n_low)[..., None]   # patchy old toning
    # leaf seams: a leaf is ~80 mm square
    a = np.arange(A, dtype=F32)[None, :]
    nleaf = max(1, int(round(A / (80 * px))))
    seam_pos = (a * nleaf / A) % 1.0
    seam = smoothstep(0.004, 0.0, np.minimum(seam_pos, 1 - seam_pos)) * (1 - burn) * 0.6
    f0 = f0 * (1 - 0.10 * seam)[..., None]
    rough = rough + 0.12 * seam
    # convexity (for wear) from the laplacian at ~1 mm
    lap = (np.roll(H, 1, 1) + np.roll(H, -1, 1) - 2 * H)
    lap0 = np.zeros_like(H)
    lap0[1:-1] = H[2:] + H[:-2] - 2 * H[1:-1]
    k = -(lap + lap0) * px * px
    convex = np.clip(k * 0.35, 0, 1)
    wear = smoothstep(0.75, 1.05, convex * 0.8 + 0.25 * n_mid + 0.15 * n_fine) * wear_amt
    metal = np.ones((S, A), F32) * (1 - wear)
    metal = metal * (1 - back)
    alb = BOLE[None, None, :] * np.ones((S, A, 1), F32)
    alb = mix(alb, np.array([0.05, 0.035, 0.022], F32), back[..., None])
    rough = np.where(wear > 0.5, 0.45, rough)

    def ao_hook(ao):
        # toning: grime and old glaze collect in the hollows (low AO), less on burnished members
        dirt = np.clip((1 - ao) * 1.3 + 0.08 * n_low - 0.06, 0, 1) * (1 - burn * 0.6)
        leaf = metal > 0.5
        # leaf areas: grime shows as a diffuse layer where the leaf is dulled; bole/back: grime mixes in
        alb2 = np.where(leaf[..., None], GRIME, mix(alb, GRIME, dirt[..., None]))
        return dict(alb=alb2.astype(F32),
                    rough=np.clip(rough + 0.25 * dirt, 0.05, 1).astype(F32),
                    f0=(f0 * (1 - 0.75 * dirt)[..., None]).astype(F32),
                    metal=np.clip(metal * (1 - 0.55 * dirt), 0, 1).astype(F32))
    return dict(alb=alb, rough=rough, f0=f0, metal=metal, ao_hook=ao_hook)


def dielectric(alb, rough, f0=0.04):
    S, A = rough.shape
    return dict(alb=alb.astype(F32), rough=rough.astype(F32),
                f0=np.full((S, A, 3), f0, F32), metal=np.zeros((S, A), F32))


# ------------------------------------------------------------------ the designs
class Design:
    name = ''
    kind = 'moulding'      # or 'liner'
    width_mm = 50.0
    lip_mm = 8.0           # sight edge height above whatever sits inside it (for the CSS cast shadow)
    h_outer = 0.0          # height outside the outer edge (wall / bezel)
    h_inner = 0.0          # height inside the sight edge
    note = ''

    def profile(self):
        raise NotImplementedError

    def ornament(self, s, a, reg, ctx):
        return None

    def material(self, ctx, H, reg):
        raise NotImplementedError


class Walnut(Design):
    name = 'walnut'
    width_mm = 70.0
    lip_mm = 9.0
    note = 'solid walnut gallery scoop, satin oil finish'

    def profile(self):
        return [
            (6.0, seg_quarter_up(0, 6, 15.5, 22.0), 1),        # outer roll
            (9.0, seg_line(6, 22.0, 9, 22.0), 1),              # top flat
            (9.6, seg_line(9, 22.0, 9.6, 21.0), 2),            # quirk
            (55.0, seg_cove(9.6, 21.0, 55, 9.5, 4.2), 3),      # the scoop
            (57.0, seg_line(55, 9.5, 57, 9.5), 3),
            (64.0, seg_bead(57, 64, 9.5, 3.3), 4),             # sight bead
            (67.5, seg_line(64, 9.5, 67.5, 9.0), 5),
            (70.0, seg_quarter_down(67.5, 70, 9.0, 4.0), 5),   # sight edge rolls into the rabbet
        ]

    def material(self, ctx, H, reg):
        rng, S, A, px = ctx['rng'], ctx['S'], ctx['A'], ctx['px_mm']
        s = ctx['s2']
        streak = spectral_noise(rng, S, A, 0.35 * px, 30 * px)
        med = spectral_noise(rng, S, A, 2.5 * px, 110 * px)
        low = spectral_noise(rng, S, A, 18 * px, 380 * px)
        warp = periodic_warp(rng, A, 240 * px, 2.2)[None, :]
        ring = (s * 0.28 + H * 1.15 + warp + 1.2 * med) / 2.9
        ringv = np.abs(((ring % 1.0) - 0.5) * 2)            # 0 at band centre
        late = smoothstep(0.55, 0.95, ringv)
        t = 0.50 + 0.20 * med + 0.08 * streak + 0.14 * low - 0.22 * late
        t = np.clip(t, 0, 1)
        dark = np.array([0.030, 0.0155, 0.0085], F32)
        light = np.array([0.150, 0.080, 0.042], F32)
        alb = dark + (light - dark) * t[..., None]
        pores = wood_pores(rng, S, A, 0.0035, 5 * SS, 0.45)
        alb = alb * pores[..., None]
        rough = 0.30 + 0.03 * streak + 0.18 * (1 - pores)
        return dielectric(alb, rough, 0.045)


class Black(Design):
    name = 'black'
    width_mm = 42.0
    lip_mm = 7.0
    note = 'black-stained ash, square gallery profile with eased edges, satin'

    def profile(self):
        return [
            (2.5, seg_quarter_up(0, 2.5, 16.0, 19.0), 1),
            (36.0, seg_round(2.5, 19.0, 36, 19.0, 0.35), 2),    # face, the faintest crown
            (38.5, seg_quarter_down(36, 38.5, 19.0, 15.5), 3),
            (40.0, seg_line(38.5, 15.5, 40, 15.5), 4),          # small step
            (42.0, seg_quarter_down(40, 42, 15.5, 11.0), 4),
        ]

    def material(self, ctx, H, reg):
        rng, S, A, px = ctx['rng'], ctx['S'], ctx['A'], ctx['px_mm']
        s = ctx['s2']
        med = spectral_noise(rng, S, A, 2 * px, 90 * px)
        fine = spectral_noise(rng, S, A, 0.3 * px, 6 * px)
        warp = periodic_warp(rng, A, 300 * px, 3.0)[None, :]
        ring = (s * 0.22 + H * 1.4 + warp + 1.5 * med) / 3.6
        rv = (ring % 1.0)
        early = smoothstep(0.0, 0.08, rv) * smoothstep(0.42, 0.30, rv)  # porous earlywood band of ash
        pores = wood_pores(rng, S, A, 0.010, 4 * SS, 1.0)
        porous = np.clip(early * (1 - pores) * 1.4 + 0.25 * early, 0, 1)
        base = np.array([0.0135, 0.0129, 0.0123], F32)
        alb = base * (1 + 0.04 * med + 0.03 * fine)[..., None] * (1 + 0.30 * porous)[..., None]
        rough = 0.42 + 0.14 * porous + 0.015 * fine
        return dielectric(alb, rough, 0.045)


