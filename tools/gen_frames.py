#!/usr/bin/env python
"""
framed: render the picture-frame mouldings and liners as lit bitmaps, and write their CSS.

Requires numpy and Pillow (python3 -m pip install numpy pillow). python -I only sees
them when they are installed for the interpreter itself, not as a user-site package.

    python -I tools/gen_frames.py            # everything (about 5-10 min)
    python -I tools/gen_frames.py walnut gilt  # only these designs (CSS is always rewritten in full)
    python -I tools/gen_frames.py --css-only     # just rewrite the generated CSS block
    python -I tools/gen_frames.py --no-css walnut  # render without touching the CSS (for previews)

Writes  framed/assets/frames/<design>-<t|b|l|r>.jpg   one strip per side, already lit for that side
        framed/css/frames.css                         everything after the GENERATED marker

Every design is a real cross-section (heights in mm, from the outer edge to the sight edge) plus an
optional ornament that repeats along the length. The renderer turns that height field into normals and
lights it the way a room lights a frame on a wall: a soft key from above and to the left (ceiling or
window, about the museum "30 degree" angle), a dim room around it (bright ceiling, mid walls, dark floor),
self-shadowing and ambient occlusion from the profile itself, and a material model per design (satin
wood, French-polished ebonised wood, burnished and matte gilding with worn bole and toned recesses,
linen). Each side gets its own render because the light falls differently on each rail: the top rail's
upward faces catch the light and its sight edge is in shade; the bottom rail is the reverse.

The strip textures tile along their length (all noise and ornament is periodic), are rendered at 2x and
box-filtered down, tone-mapped with a soft shoulder, and dithered before 8-bit quantisation so the TV
shows no banding. Texture density is 1.5x the screen's at the design's nominal width, so the default
"Frame width" is downsampled (sharp) and the widest setting is ~1:1.

Physical scale: the 55" Frame's screen is 1208.7 x 679.9 mm on a 1920 x 1080 CSS canvas
(1.5885 CSS px per mm). js/screens/art.js reads --m-mm / --l-mm from the CSS this script writes.
"""
