# ------------------------------------------------------------------ driver
def render_side(design, side, seed):
    rng = np.random.default_rng(seed)
    px = DENS * SS
    S = int(round(design.width_mm * px))
    S += S % SS
    A = TILE[side] * SS
    s = (np.arange(S, dtype=F32) + 0.5) / px
    a = np.arange(A, dtype=F32)
    h1, reg1 = eval_profile(design.profile(), s)
    s2 = np.repeat(s[:, None], A, 1)
    a2 = np.repeat(a[None, :], S, 0)
    reg = np.repeat(reg1[:, None], A, 1)
    H = np.repeat(h1[:, None], A, 1).astype(F32)
    ctx = dict(rng=rng, S=S, A=A, px_mm=px, s2=s2, side=side)
    orn = design.ornament(s2, a2, reg, ctx)
    if orn is not None:
        H = (H + orn).astype(F32)
    mat = design.material(ctx, H, reg)
    col = shade(H, mat, side, px, design.h_outer, design.h_inner)
    img = finish(col, rng)
    return orient(img, side)


def write_css(designs):
    with open(CSS_PATH, 'r', encoding='utf-8') as f:
        css = f.read()
    i = css.find(MARKER)
    head = css if i < 0 else css[:i]
    out = [MARKER + ' (do not edit by hand; edit the generator and re-run it) ===== */',
           '/* --m-mm / --l-mm: nominal width in mm (read by js/screens/art.js);',
           ' * --m-lip / --l-lip: height of the sight edge above what sits inside it, in mm (cast shadows). */']
    for d in designs:
        sel = '.art-frame[data-moulding="%s"]' % d.name if d.kind == 'moulding' else '.art-frame[data-mount="%s"]' % d.name
        cls = 'mould' if d.kind == 'moulding' else 'mount'
        var = 'm' if d.kind == 'moulding' else 'l'
        out.append('/* %s: %s */' % (d.name, d.note))
        out.append('%s { --%s-mm: %g; --%s-lip: %g; }' % (sel, var, d.width_mm, var, d.lip_mm))
        for side in 'tblr':
            out.append('%s .%s.side--%s { background-image: url("../assets/frames/%s-%s.jpg"); }' % (sel, cls, side, d.name, side))
    with open(CSS_PATH, 'w', encoding='utf-8', newline='\n') as f:
        f.write(head.rstrip('\n') + '\n\n' + '\n'.join(out) + '\n')


def main(argv):
    no_css = '--no-css' in argv
    css_only = '--css-only' in argv
    only = set(a for a in argv[1:] if not a.startswith('--'))
    os.makedirs(OUT_DIR, exist_ok=True)
    total = 0
    for di, d in enumerate(DESIGNS):
        if css_only or (only and d.name not in only):
            continue
        for si, side in enumerate('tblr'):
            t0 = time.time()
            img = render_side(d, side, seed=1000 + di * 10 + si)
            path = os.path.join(OUT_DIR, '%s-%s.jpg' % (d.name, side))
            Image.fromarray(img).save(path, quality=JPEG_Q, subsampling=0, optimize=True, progressive=False)
            sz = os.path.getsize(path)
            total += sz
            print('%-7s %s  %4dx%-4d  %6.1f KB  %.1fs' % (d.name, side, img.shape[1], img.shape[0], sz / 1024, time.time() - t0))
    if not no_css:
        write_css(DESIGNS)
        print('wrote', CSS_PATH)
    print('assets this run: %.2f MB' % (total / 1048576))


if __name__ == '__main__':
    main(sys.argv)
